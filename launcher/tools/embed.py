#!/usr/bin/env python3
"""Embed binary files as C++ byte arrays: embed.py out.h NAME=path [NAME=path ...]"""
import sys

out, items = sys.argv[1], sys.argv[2:]
with open(out, "w") as f:
    f.write("// generated by embed.py, do not edit\n#pragma once\n#include <cstddef>\n\n")
    for item in items:
        name, path = item.split("=", 1)
        data = open(path, "rb").read()
        f.write(f"alignas(16) static const unsigned char {name}[] = {{\n")
        for i in range(0, len(data), 24):
            f.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
        f.write(f"}};\nstatic const size_t {name}Size = {len(data)};\n\n")
